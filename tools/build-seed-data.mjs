#!/usr/bin/env node
// Runs the deterministic question generator and converts its JSON output into
// data/seed-questions.js — a plain <script> file that defines `SEED_QUESTIONS`
// as a global array. Using a plain script (not fetch of a .json file) means
// the app works even when index.html is opened directly via file:// (no
// server), since fetch() of local files is blocked by CORS in that mode but
// a normal <script src> is not.
//
// Usage: node tools/build-seed-data.mjs

import { execSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const GENERATOR = path.join(__dirname, "seed-generator", "generate.mjs");
const GENERATED_JSON = path.join(__dirname, "seed-generator", "out", "questions.json");
const OUT_JS = path.join(__dirname, "..", "data", "seed-questions.js");

console.log("Running question generator...");
execSync(`node "${GENERATOR}"`, { stdio: "inherit" });

const questions = JSON.parse(fs.readFileSync(GENERATED_JSON, "utf8"));
console.log(`Loaded ${questions.length} generated questions.`);

const banner = `// AUTO-GENERATED by tools/build-seed-data.mjs — do not edit by hand.
// Regenerate with: node tools/build-seed-data.mjs
// This file defines the bundled default question bank as a plain global so
// it loads via a normal <script> tag (works from file:// with no server).
`;

const body = `const SEED_QUESTIONS = ${JSON.stringify(questions)};\n`;

fs.writeFileSync(OUT_JS, banner + body);
console.log(`Wrote ${questions.length} questions to ${OUT_JS} (${(fs.statSync(OUT_JS).size / 1e6).toFixed(2)} MB).`);
